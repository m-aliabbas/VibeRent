import "server-only";
import PDFDocument from "pdfkit";
import type { AccountExpense, AccountSummary } from "@/lib/reports/account-summary";

export type Column = { label: string; width: number; align?: "left" | "right" };
export type Cell = string | number | null | undefined;
export type BandCell = { label: string; value: number; color: string; highlight?: boolean };
export type StatementSection = {
  title: string;
  columns: Column[];
  rows: Cell[][];
  /** Shaded first row, such as a brought-forward balance. */
  opening?: Cell[];
  totals?: Cell[];
  emptyText: string;
  /** Start this section on a fresh page (used for per-car owner sheets). */
  newPage?: boolean;
};

export type StatementInput = {
  agency: string;
  address?: string | null;
  phone?: string | null;
  title: string;
  period: string;
  band: BandCell[];
  bandNote?: string;
  sections: StatementSection[];
};

const LEFT = 42;
const WIDTH = 511;
const BOTTOM = 756;
const ROW = 17;

/**
 * One statement design for every ledger PDF (customer, driver, owner, agency):
 * agency header, coloured summary band, then gridded sheet-style tables.
 */
export async function createStatementPdf(input: StatementInput) {
  const doc = new PDFDocument({ size: "A4", margin: 42, bufferPages: true, info: { Title: input.title, Author: input.agency } });
  const chunks: Buffer[] = [];
  const completed = new Promise<Buffer>((resolve, reject) => {
    doc.on("data", (chunk) => chunks.push(Buffer.from(chunk)));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });

  header(doc, input);
  summaryBand(doc, input.band, input.bandNote);
  for (const item of input.sections) {
    section(doc, input, item);
    table(doc, input, item);
  }

  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    doc.font("Helvetica").fontSize(7).fillColor("#98A2B3").text(`Generated by VibeRent | ${input.period} | Page ${i - range.start + 1} of ${range.count}`, LEFT, 788, { width: WIDTH, align: "center", lineBreak: false });
  }
  doc.end();
  return completed;
}

type AccountLedgerInput = Omit<StatementInput, "band" | "bandNote" | "sections"> & {
  columns: Column[];
  rows: Cell[][];
  opening?: Cell[];
  totals?: Cell[];
  summary: AccountSummary;
  expenses: AccountExpense[];
  emptyText: string;
  tableTitle?: string;
};

/** Customer and driver statements: rentals, then expenses with what was returned. */
export function createAccountLedgerPdf(input: AccountLedgerInput) {
  const { columns, rows, opening, totals, summary, expenses, emptyText, tableTitle = "Rentals", ...rest } = input;
  return createStatementPdf({
    ...rest,
    band: [
      { label: "RENT", value: summary.rent, color: "#006FE6" },
      { label: "RECEIVED", value: summary.received, color: "#006FE6" },
      { label: "EXPENSES", value: summary.expenses, color: "#B42318" },
      { label: "RETURNED", value: summary.recovered, color: "#067647" },
      { label: "NET INCOME", value: summary.net, color: "#DC6803", highlight: true },
    ],
    bandNote: "Net income = received - (expenses - returned). Expenses are approved costs linked to these rentals; returned is money paid back to the agency.",
    sections: [
      { title: tableTitle, columns, rows, opening, totals, emptyText },
      expenseSection(expenses, "No approved expenses linked in this period."),
    ],
  });
}

/** Expenses with the amount returned against each, shared by every statement type. */
export function expenseSection(expenses: AccountExpense[], emptyText: string, title = "Expenses and recoveries"): StatementSection {
  const amount = expenses.reduce((sum, row) => sum + row.amount, 0);
  const recovered = expenses.reduce((sum, row) => sum + row.recovered, 0);
  return {
    title,
    columns: [
      { label: "Date", width: 58 },
      { label: "Car", width: 62 },
      { label: "Head / description", width: 196 },
      { label: "Expense", width: 65, align: "right" },
      { label: "Returned", width: 65, align: "right" },
      { label: "Net", width: 65, align: "right" },
    ],
    rows: expenses.map((row) => [sheetDate(row.date), row.plate ?? "", `${row.head}: ${row.description}`, number(row.amount), row.recovered ? number(row.recovered) : "", number(row.amount - row.recovered)]),
    totals: expenses.length ? ["Total", "", "", number(amount), number(recovered), number(amount - recovered)] : undefined,
    emptyText,
  };
}

function header(doc: PDFKit.PDFDocument, input: StatementInput) {
  doc.font("Helvetica-BoldOblique").fontSize(15).fillColor("#006FE6").text(input.agency.toUpperCase(), LEFT, 44, { width: 300 });
  if (input.address) doc.font("Helvetica-Bold").fontSize(8.5).fillColor("#19191F").text(input.address, LEFT, doc.y + 2, { width: 300 });
  if (input.phone) doc.font("Helvetica").fontSize(8.5).fillColor("#344054").text(input.phone, LEFT, doc.y + 1, { width: 300 });
  const after = doc.y;
  doc.font("Helvetica-Bold").fontSize(12).fillColor("#19191F").text(input.title, 353, 44, { width: 200, align: "right" });
  doc.font("Helvetica").fontSize(8.5).fillColor("#475467").text(input.period, 353, doc.y + 2, { width: 200, align: "right" });
  doc.y = Math.max(after, doc.y) + 14;
}

function summaryBand(doc: PDFKit.PDFDocument, cells: BandCell[], note?: string) {
  const y = doc.y;
  const width = WIDTH / cells.length;
  cells.forEach((cell, index) => {
    const x = LEFT + index * width;
    doc.rect(x, y, width, 15).fill(cell.color);
    doc.font("Helvetica-Bold").fontSize(7).fillColor("#FFFFFF").text(cell.label, x, y + 4.5, { width, align: "center", lineBreak: false });
    doc.rect(x, y + 15, width, 20).fill(cell.highlight ? "#FFF6ED" : "#FFFFFF");
    doc.font("Helvetica-Bold").fontSize(9.5).fillColor(cell.value < 0 ? "#B42318" : "#19191F").text(signed(cell.value), x, y + 21, { width, align: "center", lineBreak: false });
  });
  doc.lineWidth(0.6).strokeColor("#98A2B3").rect(LEFT, y, WIDTH, 35).stroke();
  for (let index = 1; index < cells.length; index++) doc.moveTo(LEFT + index * width, y).lineTo(LEFT + index * width, y + 35).stroke();
  if (note) doc.font("Helvetica").fontSize(6.8).fillColor("#667085").text(note, LEFT, y + 40, { width: WIDTH });
  doc.y = y + (note ? 58 : 48);
}

function section(doc: PDFKit.PDFDocument, input: StatementInput, item: StatementSection) {
  if (item.newPage || doc.y + 60 > BOTTOM) {
    doc.addPage();
    continuationHeader(doc, input);
  }
  doc.font("Helvetica-Bold").fontSize(10.5).fillColor("#19191F").text(item.title, LEFT, doc.y);
  doc.y += 5;
}

function continuationHeader(doc: PDFKit.PDFDocument, input: StatementInput) {
  doc.font("Helvetica-BoldOblique").fontSize(10).fillColor("#006FE6").text(input.agency.toUpperCase(), LEFT, 44, { width: 300, lineBreak: false });
  doc.font("Helvetica-Bold").fontSize(9).fillColor("#19191F").text(input.title, 353, 44, { width: 200, align: "right", lineBreak: false });
  doc.moveTo(LEFT, 60).lineTo(LEFT + WIDTH, 60).lineWidth(0.6).strokeColor("#98A2B3").stroke();
  doc.y = 70;
}

function table(doc: PDFKit.PDFDocument, input: StatementInput, item: StatementSection) {
  const { columns } = item;
  const head = () => {
    const y = doc.y;
    let x = LEFT;
    for (const column of columns) {
      doc.rect(x, y, column.width, 18).fill("#344054");
      doc.font("Helvetica-Bold").fontSize(7.5).fillColor("#FFFFFF").text(column.label, x + 4, y + 5.5, { width: column.width - 8, align: column.align ?? "left", lineBreak: false });
      x += column.width;
    }
    doc.y = y + 18;
  };
  const line = (cells: Cell[], fill?: string, bold = false) => {
    if (doc.y + ROW > BOTTOM) {
      doc.addPage();
      continuationHeader(doc, input);
      doc.font("Helvetica-Bold").fontSize(9).fillColor("#19191F").text(`${item.title} (continued)`, LEFT, doc.y);
      doc.y += 4;
      head();
    }
    const y = doc.y;
    if (fill) doc.rect(LEFT, y, WIDTH, ROW).fill(fill);
    let x = LEFT;
    columns.forEach((column, index) => {
      const value = cells[index];
      doc.font(bold ? "Helvetica-Bold" : "Helvetica").fontSize(7.5).fillColor("#19191F");
      doc.text(fit(doc, value === null || value === undefined ? "" : String(value), column.width - 8), x + 4, y + 5, { width: column.width - 8, align: column.align ?? "left", lineBreak: false });
      x += column.width;
    });
    doc.lineWidth(0.4).strokeColor("#98A2B3").rect(LEFT, y, WIDTH, ROW).stroke();
    x = LEFT;
    for (const column of columns.slice(0, -1)) {
      x += column.width;
      doc.moveTo(x, y).lineTo(x, y + ROW).stroke();
    }
    doc.y = y + ROW;
  };
  head();
  if (item.opening) line(item.opening, "#F8FAFC", true);
  if (!item.rows.length) {
    doc.font("Helvetica").fontSize(8.5).fillColor("#667085").text(item.emptyText, LEFT, doc.y + 8, { width: WIDTH, align: "center" });
    doc.y += 14;
  }
  item.rows.forEach((row, index) => line(row, index % 2 ? "#FCFCFD" : undefined));
  if (item.totals) line(item.totals, "#EAF4FF", true);
  doc.y += 16;
}

export function sheetDate(value: string) {
  const [year, month, day] = value.slice(0, 10).split("-");
  return `${Number(day)}-${Number(month)}-${year}`;
}
export function number(value: number) {
  return Math.abs(value).toLocaleString("en-PK");
}
export function signed(value: number) {
  return `${value < 0 ? "-" : ""}${number(value)}`;
}

/** Trims text to one line of the cell with an ellipsis, using the current font metrics. */
function fit(doc: PDFKit.PDFDocument, value: string, width: number) {
  if (doc.widthOfString(value) <= width) return value;
  let text = value;
  while (text.length > 1 && doc.widthOfString(`${text}...`) > width) text = text.slice(0, -1);
  return `${text.trimEnd()}...`;
}
