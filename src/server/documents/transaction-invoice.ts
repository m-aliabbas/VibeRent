import "server-only";

import PDFDocument from "pdfkit";

export type InvoiceLine = { label: string; value: string };

export async function createTransactionInvoice(input: {
  agency: string;
  title: string;
  reference: string;
  recipient: string;
  issuedAt: string;
  lines: InvoiceLine[];
  amountLabel?: string;
  amount?: number;
  note?: string;
}): Promise<Buffer> {
  const doc = new PDFDocument({
    size: "A4",
    margin: 48,
    info: { Title: `${input.title} ${input.reference}`, Author: input.agency },
  });
  const chunks: Buffer[] = [];
  const completed = new Promise<Buffer>((resolve, reject) => {
    doc.on("data", chunk => chunks.push(Buffer.from(chunk)));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });

  doc.font("Helvetica-Bold").fontSize(20).fillColor("#19191F").text(input.agency);
  doc.font("Helvetica").fontSize(9).fillColor("#667085").text("Generated by VibeRent");
  doc.moveDown(1.2);
  doc.rect(48, doc.y, 499, 4).fill("#006FE6");
  doc.moveDown(1.4);
  doc.font("Helvetica-Bold").fontSize(18).fillColor("#006FE6").text(input.title);
  doc.moveDown(0.4);
  doc.font("Helvetica").fontSize(9).fillColor("#475467")
    .text(`Reference: ${input.reference}`)
    .text(`Issued: ${formatDate(input.issuedAt)}`)
    .text(`For: ${input.recipient}`);
  doc.moveDown(1.4);

  for (const line of input.lines) {
    const y = doc.y;
    doc.roundedRect(48, y, 499, 34, 5).fill("#F8FAFC");
    doc.font("Helvetica").fontSize(8).fillColor("#667085").text(line.label, 60, y + 7, { width: 180 });
    doc.font("Helvetica-Bold").fontSize(10).fillColor("#19191F").text(line.value, 245, y + 7, { width: 290, align: "right" });
    doc.y = y + 42;
  }

  if (input.amount !== undefined) {
    doc.moveDown(0.5);
    doc.roundedRect(295, doc.y, 252, 54, 7).fill("#EFF8FF");
    const y = doc.y;
    doc.font("Helvetica").fontSize(9).fillColor("#475467").text(input.amountLabel ?? "Amount", 310, y + 10, { width: 220, align: "right" });
    doc.font("Helvetica-Bold").fontSize(17).fillColor("#006FE6").text(money(input.amount), 310, y + 26, { width: 220, align: "right" });
    doc.y = y + 68;
  }
  if (input.note) doc.font("Helvetica").fontSize(9).fillColor("#475467").text(input.note, { lineGap: 2 });
  doc.font("Helvetica").fontSize(8).fillColor("#98A2B3").text("This document is an operational receipt generated from VibeRent records.", 48, 780, { width: 499, align: "center" });
  doc.end();
  return completed;
}

function money(value: number) {
  return `PKR ${value.toLocaleString("en-PK")}`;
}

function formatDate(value: string) {
  return new Intl.DateTimeFormat("en-PK", { dateStyle: "medium", timeStyle: "short", timeZone: "Asia/Karachi" }).format(new Date(value));
}
